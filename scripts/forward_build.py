#!/usr/bin/env python3
"""Render the forward-slate site layer (forward/**) from data/forward/*.json.

Writes four static pages into forward/:
  index.html    — window overview, KPIs, gap status, featured picks summary
  matches.html  — every row of the forward slate (originated and unlined)
  picks.html    — the bespoke high-confidence write-ups
  gaps.html     — the forward gap flags (VF-14 / VF-15 / VF-20 / VF-22)

Pages are generated from data files only; nothing is hand-edited in forward/
after a build. Root navigation is NOT touched: a nav-link request is logged in
COORDINATION.md while other live sessions hold the root pages.
"""
from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FWD = ROOT / "data" / "forward"
OUT = ROOT / "forward"

NAV = [
    ("index.html", "Overview &amp; Slate"),
    ("matches.html", "All Matches"),
    ("picks.html", "High-Confidence Picks"),
    ("gaps.html", "Gap Flags"),
]


def esc(x) -> str:
    if x is None:
        return "—"
    return html.escape(str(x))


def page(title: str, active: str, body: str) -> str:
    nav_html = "\n".join(
        f'        <a href="{href}" class="{"active" if href == active else ""}">{label}</a>'
        for href, label in NAV
    )
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} — OLBG Forward Slate Desk</title>
  <link rel="stylesheet" href="assets/style.css">
</head>
<body>
  <header class="topbar">
    <div class="topbar-inner">
      <a class="brand" href="index.html">
        <span>OLBG Forward Slate Origination Desk</span>
        <span class="brand-badge">Window 2026-10-23 → 2026-11-02</span>
      </a>
      <nav class="nav" aria-label="Forward slate navigation">
{nav_html}
      </nav>
    </div>
  </header>
  <div class="subbar">
    <div class="subbar-inner">
      <span><strong>Cross-Layer Navigation:</strong></span>
      <a href="../index.html">Root Dashboard (/)</a>
      <span>·</span>
      <a href="../verified/index.html">Verified Desk (/verified/)</a>
      <span>·</span>
      <a href="../live/index.html">Live Slate (/live/)</a>
      <span>·</span>
      <a href="../survey/index.html">All-Sports Survey (/survey/)</a>
    </div>
  </div>
  <main class="container">
{body}
  </main>
  <footer class="footer">
    <p>Forward slate layer generated by <code>scripts/forward_build.py</code> from
    <code>data/forward/</code> captures. Every market is independently originated from
    official-source team statistics — no bookmaker odds or tipster consensus percentages
    enter any equation. Rows whose official inputs could not be verified ship unlined with
    an explicit reason.</p>
  </footer>
</body>
</html>
"""


def odds_cell(m: dict | None, key_p: str, key_o: str) -> str:
    if not m:
        return '<td class="num muted">—</td><td class="num muted">—</td>'
    return f'<td class="num">{m[key_p]:.4f}</td><td class="num">{m[key_o]:.2f}</td>'


def matches_table(rows: list[dict]) -> str:
    tr = []
    for r in rows:
        pick = r.get("pick") or {}
        feat = r.get("featured")
        if r["line_status"] == "originated":
            wm = r["winner_market"]
            sel = esc(pick.get("selection"))
            conf = esc(pick.get("confidence"))
            badge = ' <span class="chip chip-band">in-band</span>' if feat else ""
            tr.append(f"""      <tr>
        <td>{esc(r['date'])}<br><span class="muted small">{esc(r['time'])}</span></td>
        <td><strong>{esc(r['away'])}</strong> @ <strong>{esc(r['home'])}</strong><br>
            <span class="muted small">{esc(r['competition'])} · {esc(r['venue'])}</span></td>
        <td class="small">{esc(r['away_summary'])}<br>{esc(r['home_summary'])}</td>
        <td class="num">{wm['away_prob']:.4f}<br>{wm['home_prob']:.4f}</td>
        <td class="num">{wm['away_odds']:.2f}<br>{wm['home_odds']:.2f}</td>
        <td class="num">{r['handicap_market']['line']:+.1f}</td>
        <td class="num">{r['total_market']['line']:.1f}<br><span class="muted small">{r['total_market']['projected']:.2f} proj</span></td>
        <td class="small">{sel} <span class="chip chip-{conf}">{conf}</span>{badge}</td>
        <td class="small"><a href="{esc(r['official_url'])}">official</a></td>
      </tr>""")
        else:
            tr.append(f"""      <tr class="unlined">
        <td>{esc(r['date'])}<br><span class="muted small">{esc(r['time'])}</span></td>
        <td><strong>{esc(r['away'])}</strong> @ <strong>{esc(r['home'])}</strong><br>
            <span class="muted small">{esc(r['competition'])} · {esc(r['venue'])}</span></td>
        <td colspan="6" class="small">Unlined — {esc(r['blank_reason'])}</td>
        <td class="small"><a href="{esc(r['official_url'])}">official</a></td>
      </tr>""")
    return """    <table class="grid">
      <thead>
        <tr><th>Date / Time (UTC)</th><th>Fixture</th><th>Form (W-L-OTL / GF-GA)</th>
        <th>Prob H/A</th><th>Fair H/A</th><th>Hcap</th><th>Total</th><th>Pick</th><th>Source</th></tr>
      </thead>
      <tbody>
""" + "\n".join(tr) + "\n      </tbody>\n    </table>"


def build() -> None:
    matches = json.loads((FWD / "matches.json").read_text(encoding="utf-8"))
    preds = json.loads((FWD / "predictions.json").read_text(encoding="utf-8"))
    flagged = json.loads((FWD / "flagged.json").read_text(encoding="utf-8"))
    rows = matches["matches"]
    counts = matches["counts"]

    featured_rows = [r for r in rows if r.get("featured")]

    hero = """
<section class="hero">
  <p class="eyebrow">Forward-Window Slate Capture &amp; Line Origination</p>
  <h1>OLBG Forward Slate Desk — 23 Oct to 2 Nov 2026</h1>
  <p>The complete official <strong>NHL</strong> game-week card for 2026-10-23 → 2026-11-02,
  the full <strong>2026 MLB World Series</strong> schedule including the Game 4 the verified
  layer never lined (VF-15), and every <strong>EuroCup Round 5</strong> fixture (VF-20) —
  captured live from official league feeds on 2026-10-22 and priced with the same independent
  methodology as the verified desk. High-confidence picks sit between <strong>-250 and +10000
  American</strong> at a &gt;70% model probability; anything unverifiable is left blank and
  flagged (VF-14, VF-22), never inferred.</p>
</section>
"""
    kpis = f"""
<div class="kpi-grid">
  <div class="kpi"><div class="kpi-val">{counts['total']}</div><div class="kpi-label">Forward Slate Rows</div></div>
  <div class="kpi"><div class="kpi-val">{counts['originated']}</div><div class="kpi-label">Originated Lines (NHL + MLB)</div></div>
  <div class="kpi"><div class="kpi-val">{counts['nhl']}</div><div class="kpi-label">NHL Fixtures (complete game-week card)</div></div>
  <div class="kpi"><div class="kpi-val">{counts['mlb']}</div><div class="kpi-label">MLB World Series Games (G4 gap closed)</div></div>
  <div class="kpi"><div class="kpi-val">{counts['eurocup']}</div><div class="kpi-label">EuroCup R5 Fixtures (card closed, unlined)</div></div>
  <div class="kpi"><div class="kpi-val">{counts['band_picks']}</div><div class="kpi-label">In-Band High-Confidence Picks (−250..+10000)</div></div>
</div>
"""
    gap_items = "\n".join(
        f"""    <div class="card">
      <h3><span class="chip chip-{ 'ok' if 'closed' in it['status'] or 'complete' in it['status'] else 'warn' }">{esc(it['id'])}</span> {esc(it['title'])}</h3>
      <p class="small muted">Status: {esc(it['status'])}</p>
      <p>{esc(it['summary'])}</p>
    </div>"""
        for it in flagged["items"]
    )
    feat_cards = "\n".join(
        f"""    <div class="card">
      <h3>{esc(p['selection'])} <span class="chip chip-high">{esc(p['confidence'])} · {p['probability'] * 100:.1f}% · {p['fair_american']:+d}</span></h3>
      <p class="small muted">{esc(p['event'])} · {esc(p['competition'])} · {esc(p['time'])}</p>
      <p><strong>{esc(p['headline'])}</strong></p>
      <p>{esc(p['text'])}</p>
      <p class="small"><a href="picks.html">Full write-up &amp; sources →</a></p>
    </div>"""
        for p in preds["predictions"][:3]
    )
    index_body = hero + kpis + f"""
<div class="section-head">
  <h2>Named Gap Closures</h2>
  <p>Task-board items attempted against live official feeds during the 2026-10-22 capture window.
  <a href="gaps.html">Full flag log →</a></p>
</div>
{gap_items}

<div class="section-head">
  <h2>Featured High-Confidence Picks (sample)</h2>
  <p><a href="picks.html">All {counts['band_picks']} bespoke write-ups →</a> ·
     <a href="matches.html">All {counts['total']} slate rows →</a></p>
</div>
{feat_cards}
"""

    matches_body = f"""
<section class="hero">
  <p class="eyebrow">Complete Forward Slate</p>
  <h1>All Matches — 23 Oct to 2 Nov 2026</h1>
  <p>{counts['originated']} originated rows with independent winner, handicap and total markets,
  plus {counts['unlined']} EuroCup Round 5 fixtures carried unlined because the official standings
  endpoints returned no data — never inferred.</p>
</section>
{matches_table(rows)}
"""

    pred_card_list = []
    for p in preds["predictions"]:
        facts_html = "\n".join(
            f'          <li>{esc(f["claim"])} — <a href="{esc(f["source"])}">{esc(f["source"])}</a></li>'
            for f in p["facts"]
        )
        pred_card_list.append(
            f"""    <div class="card pred">
      <h3>{esc(p['selection'])}</h3>
      <p class="small muted">{esc(p['event'])} · {esc(p['competition'])} · kickoff {esc(p['time'])}</p>
      <p class="small">Market: <strong>{esc(p['market'])}</strong> · Model probability
        <strong>{p['probability'] * 100:.1f}%</strong> · Fair decimal <strong>{p['fair_odds']:.2f}</strong>
        · Fair American <strong>{p['fair_american']:+d}</strong> · Confidence
        <span class="chip chip-high">{esc(p['confidence'])}</span> · {p['word_count']} words</p>
      <h4>{esc(p['headline'])}</h4>
      <p>{esc(p['text'])}</p>
      <details>
        <summary>Official-source facts ({len(p['facts'])})</summary>
        <ul class="facts">
{facts_html}
        </ul>
      </details>
      <p class="small"><a href="{esc(p['official_url'])}">Official match page</a></p>
    </div>"""
        )
    pred_cards = "\n".join(pred_card_list)
    picks_body = f"""
<section class="hero">
  <p class="eyebrow">Uniform High-Confidence Gate</p>
  <h1>High-Confidence Picks — Forward Window</h1>
  <p>A pick qualifies only when the model probability is <strong>≥ 70%</strong> and the fair
  American price is between <strong>-250 and +10000</strong>, so every headline here is a genuine
  &gt;70% shot that is not priced into ultra-short territory. Each write-up is bespoke, at least
  30 words, and names the team, a player, current form and the explicit betting selection, with
  every figure sourced to an official feed. {preds['count']} of {counts['total']} rows clear the gate.</p>
</section>
{pred_cards}
"""

    gap_cards_list = []
    for it in flagged["items"]:
        sources = it.get("sources") or []
        src_html = ""
        if sources:
            links = ", ".join(f'<a href="{esc(s)}">{esc(s)}</a>' for s in sources)
            src_html = f'<p class="small">Sources: {links}</p>'
        gap_cards_list.append(
            f"""    <div class="card">
      <h3><span class="chip chip-warn">{esc(it['id'])}</span> {esc(it['title'])}</h3>
      <p class="small muted">Status: {esc(it['status'])}</p>
      <p>{esc(it['summary'])}</p>
      {src_html}
    </div>"""
        )
    gap_cards = "\n".join(gap_cards_list)
    gaps_body = f"""
<section class="hero">
  <p class="eyebrow">Forward Gap Flags</p>
  <h1>Named Gaps — Status After This Window's Capture</h1>
  <p>Where the official feeds did not deliver, the desk says so and leaves the rows blank.
  Attempt logs live in <code>data/forward/capture_gap_notes.json</code>.</p>
</section>
{gap_cards}
"""

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "index.html").write_text(page("Overview &amp; Slate", "index.html", index_body), encoding="utf-8")
    (OUT / "matches.html").write_text(page("All Matches", "matches.html", matches_body), encoding="utf-8")
    (OUT / "picks.html").write_text(page("High-Confidence Picks", "picks.html", picks_body), encoding="utf-8")
    (OUT / "gaps.html").write_text(page("Gap Flags", "gaps.html", gaps_body), encoding="utf-8")
    print(f"wrote forward/: index.html, matches.html, picks.html, gaps.html ({counts['total']} rows)")


if __name__ == "__main__":
    build()
